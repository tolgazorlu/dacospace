#!/usr/bin/env node
// Copies the public reading material of java-scale-lab and ai-systems-lab into content/, for the hosted
// demo. Allowlist only: markdown lessons, missions, case files, questions and the roadmap tables. Never
// code, results, docs or the personal progress log. Fails if a file looks like it holds a secret or a
// machine path. Usage: node scripts/sync-content.mjs [labDir] [aiLabDir]
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const labDir = path.resolve(process.argv[2] ?? process.env.DACOSPACE_LAB_DIR ?? path.join(root, "..", "java-scale-lab"))
const aiDir = path.resolve(process.argv[3] ?? process.env.DACOSPACE_AI_LAB_DIR ?? path.join(root, "..", "ai-systems-lab"))
const out = path.resolve(process.env.DACOSPACE_CONTENT_OUT ?? path.join(root, "content"))

const SUSPICIOUS = [/\/Users\/[a-z]/i, /\/home\/[a-z]/, /[\w.+-]+@(gmail|hotmail|yahoo|outlook|icloud)\./i, /\bsk-[A-Za-z0-9_-]{16,}/, /\bghp_[A-Za-z0-9]{20,}/, /BEGIN [A-Z ]*PRIVATE KEY/]

function check(file, text) {
  for (const re of SUSPICIOUS) if (re.test(text)) throw new Error(`${file}: matches ${re}, refusing to publish it`)
}

/** Roadmap table only, every mission reset to todo: the snapshot must not carry anyone's progress. */
function sanitizeProgress(text, resetStatus) {
  const lines = []
  for (const line of text.split("\n")) {
    if (/^## Log/.test(line)) break
    if (/^- \d{4}-\d{2}-\d{2} \[\d{2}\]/.test(line)) continue
    const row = line.match(/^\|\s*(\d{2})\s*\|(.*)\|\s*$/)
    if (row && resetStatus) {
      const cells = row[2].split("|").map((c) => c.trim())
      lines.push(`| ${row[1]} | ${cells[0]} | ${cells[1]} | todo | - |`)
    } else lines.push(line)
  }
  return lines.join("\n").trimEnd() + "\n"
}

function copyDir(src, dest, accept) {
  if (!fs.existsSync(src)) throw new Error(`missing ${src}`)
  fs.mkdirSync(dest, { recursive: true })
  let n = 0
  for (const f of fs.readdirSync(src).sort()) {
    if (!accept.test(f)) continue
    const text = fs.readFileSync(path.join(src, f), "utf8")
    check(path.join(src, f), text)
    fs.writeFileSync(path.join(dest, f), text)
    n++
  }
  return n
}

function snapshot(src, name, dirs, resetStatus) {
  const dest = path.join(out, name)
  fs.rmSync(dest, { recursive: true, force: true })
  const counts = Object.fromEntries(dirs.map(([d, re]) => [d, copyDir(path.join(src, d), path.join(dest, d), re)]))
  const progress = sanitizeProgress(fs.readFileSync(path.join(src, "PROGRESS.md"), "utf8"), resetStatus)
  check(path.join(src, "PROGRESS.md"), progress)
  fs.writeFileSync(path.join(dest, "PROGRESS.md"), progress)
  console.log(name, counts)
}

const NN_MD = /^\d{2}-[a-z0-9-]+\.md$/
const SLUG_MD = /^[a-z0-9]+(?:-[a-z0-9]+)*\.md$/
snapshot(labDir, "java-scale-lab", [["lessons", NN_MD], ["labs", NN_MD]], true)
snapshot(aiDir, "ai-systems-lab", [["lessons", NN_MD], ["cases", SLUG_MD], ["questions", SLUG_MD]], false)
fs.writeFileSync(
  path.join(out, "README.md"),
  `# content/

Generated by \`pnpm sync-content\` from java-scale-lab and ai-systems-lab. Do not edit here: change the
source repo, then re-run the script. The hosted demo reads this folder; local mode reads the checkouts.

This material is © Tolga Zorlu and is not covered by this repository's MIT license.
`,
)
