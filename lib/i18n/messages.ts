export const LANGS = ["en", "tr"] as const
export type Lang = (typeof LANGS)[number]
export const LANG_COOKIE = "lang"

export const messages = (lang: Lang): Messages => (lang === "tr" ? tr : en)

/** Cookie wins; otherwise Turkish browsers get Turkish, everyone else English. */
export function pickLang(cookie: string | undefined, acceptLanguage: string | null): Lang {
  if (cookie === "tr" || cookie === "en") return cookie
  return /^\s*tr\b/i.test(acceptLanguage ?? "") ? "tr" : "en"
}
